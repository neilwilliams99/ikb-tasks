-- IKB Tasks: Loans tab.
--
-- One row per loan, as it stands today: the tab looks forward from the
-- current month, so balance, offset and term are what is owed / held / left
-- now. Amounts are stored as positive figures; rate and tax rate are percent.
--   repayment     null = calculated (standard P&I repayment, or the interest
--                 for interest-only); otherwise the fixed amount paid
--   io_years      interest-only loans: years left before reverting to P&I,
--                 null = interest-only for the whole term
--   events        dated changes, [{ "month": "YYYY-MM", "type": "rate" |
--                 "offset" | "lump", "value": number }]
-- loan_settings holds the single tax rate used for every deductible loan.
--
-- Access is the same ikb_tasks_users policy as the other tables.
-- Roll back with 20261021_loans_rollback.sql.

begin;

create table if not exists public.loans (
  id              bigint generated by default as identity primary key,
  name            text not null,
  balance         numeric not null default 0,
  rate            numeric not null default 0,
  term_years      numeric not null default 30,
  repayment_type  text not null default 'pi' check (repayment_type in ('pi', 'io')),
  io_years        numeric,
  repayment       numeric,
  repayment_freq  text not null default 'monthly' check (repayment_freq in ('weekly', 'fortnightly', 'monthly')),
  extra           numeric not null default 0,
  extra_freq      text not null default 'weekly' check (extra_freq in ('weekly', 'fortnightly', 'monthly')),
  offset_balance  numeric not null default 0,
  tax_deductible  boolean not null default false,
  events          jsonb not null default '[]'::jsonb,
  notes           text,
  sort_order      integer not null default 0,
  archived_at     timestamptz,
  created_at      timestamptz not null default now()
);

create table if not exists public.loan_settings (
  id        integer primary key default 1 check (id = 1),
  tax_rate  numeric not null default 39
);
insert into public.loan_settings (id) values (1) on conflict (id) do nothing;

do $$
declare
  t text;
begin
  foreach t in array array['loans', 'loan_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('drop policy if exists ikb_tasks_users on public.%I', t);
    execute format(
      'create policy ikb_tasks_users on public.%I for all to authenticated using (public.ikb_tasks_allowed()) with check (public.ikb_tasks_allowed())',
      t
    );
  end loop;
end $$;

commit;
